"""Training curves, the A/B/C comparison table, pair examples and outlier enrichment.

Writes results/training_curves.png, results/comparison.md, results/curves.csv.
"""
from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from common import OUT, RESULTS

COLORS = {"A": "#7f7f7f", "B": "#1f77b4", "C": "#d62728"}
LABEL = {"A": "A  R+Z", "B": "B  +q, M", "C": "C  +q, M, local s_i"}


def curves() -> pd.DataFrame:
    rows = []
    for run in sorted((OUT / "runs").iterdir()):
        f = run / "results" / f"{run.name}_run-1_train.txt"
        if not f.is_file():
            continue
        regime, letter, seed = run.name.split("_")
        for line in f.read_text().splitlines():
            d = json.loads(line)
            if d.get("mode") != "eval":
                continue
            ep = -1 if d.get("epoch") is None else int(d["epoch"])
            rows.append({"run": run.name, "regime": regime, "model": letter, "seed": seed, "epoch": ep,
                         "loss": d["loss"], "E_mae": 1000 * d["mae_e_per_atom"],
                         "E_rmse": 1000 * d["rmse_e_per_atom"], "F_mae": 1000 * d["mae_f"],
                         "F_rmse": 1000 * d["rmse_f"]})
    return pd.DataFrame(rows)


def main() -> None:
    c = curves()
    c.to_csv(RESULTS / "curves.csv", index=False)
    regimes = [r for r in ("fixed", "ref") if r in set(c.regime)]
    fig, axes = plt.subplots(len(regimes), 3, figsize=(14, 4 * len(regimes)), squeeze=False)
    for row, regime in enumerate(regimes):
        for col, (key, lab) in enumerate([("F_rmse", "force RMSE (meV/Å)"),
                                          ("E_rmse", "energy RMSE (meV/atom)"), ("loss", "loss")]):
            ax = axes[row, col]
            for run, g in c[c.regime == regime].groupby("run"):
                m = g.model.iloc[0]
                ax.plot(g.epoch.clip(lower=0), g[key], color=COLORS[m],
                        ls="-" if g.seed.iloc[0] == "s1" else "--", label=f"{LABEL[m]} ({g.seed.iloc[0]})")
            ax.set_yscale("log"); ax.set_xlabel("epoch"); ax.set_ylabel(lab)
            ax.set_title(f"{regime}: {lab} on the 60 training frames")
            if col == 0:
                ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(RESULTS / "training_curves.png", dpi=130)

    out = ["# A/B/C comparison (generated by s7_report.py)", ""]
    last = c.sort_values("epoch").groupby("run").tail(1)
    out += ["## Final EMA metrics on the 60 training frames (MACE's own evaluation)", "",
            "| regime | model | seed | epoch | E MAE | E RMSE | F MAE | F RMSE |", "|---|---|---|---:|---:|---:|---:|---:|"]
    for _, r in last.sort_values(["regime", "model", "seed"]).iterrows():
        out.append(f"| {r.regime} | {LABEL[r.model]} | {r.seed} | {r.epoch} | {r.E_mae:.2f} | {r.E_rmse:.2f} | "
                   f"{r.F_mae:.1f} | {r.F_rmse:.1f} |")
    out += ["", "E in meV/atom, F in meV/Å."]

    p = RESULTS / "predictions.csv"
    if p.is_file():
        d = pd.read_csv(p)
        zero = d[(d.variant == "true")].drop_duplicates(["split", "k"])
        out += ["", "## Frame-level evaluation of the final models (train = 60 memorized; heldout = other 90)", "",
                "| regime | model | split | input | E MAE | E RMSE | F MAE | F RMSE | zero-force F RMSE |",
                "|---|---|---|---|---:|---:|---:|---:|---:|"]
        for (regime, model, split, variant), g in d.groupby(["regime", "model", "split", "variant"]):
            z = zero[zero.split == split]
            out.append(
                f"| {regime} | {LABEL[model]} | {split} | {'true s_i' if variant == 'true' else 's_i shifted 5 sites'} | "
                f"{g.dE_meV_atom.abs().mean():.2f} | {np.sqrt((g.dE_meV_atom ** 2).mean()):.2f} | "
                f"{g.F_mae_meV_A.mean():.1f} | {np.sqrt((g.F_rmse_meV_A ** 2).mean()):.1f} | "
                f"{np.sqrt((z.F_ref_rms_meV_A ** 2).mean()):.1f} |")
        out += ["", "Values are averaged over seeds in each row group.", "",
                "## Outlier enrichment (fixed regime, train split, true inputs)", ""]
        t = d[(d.regime == "fixed") & (d.split == "train") & (d.variant == "true")]
        if len(t):
            out += ["| model | frames | F RMSE: 0 antiparallel | 1 antiparallel | with weak (<1) site | "
                    "first frame | final frame | worst-5 frames: n_negative / tag |", "|---|---:|---:|---:|---:|---:|---:|---|"]
            for model, g in t.groupby("model"):
                f = lambda s: f"{np.sqrt((s.F_rmse_meV_A ** 2).mean()):.1f}" if len(s) else "-"
                per = g.groupby("k").agg(F=("F_rmse_meV_A", "mean"), neg=("n_negative", "first"),
                                         tag=("tag", "first")).sort_values("F", ascending=False).head(5)
                worst = ", ".join(f"{int(r.neg)}/{r.tag}" for _, r in per.iterrows())
                out.append(f"| {LABEL[model]} | {g.k.nunique()} | {f(g[g.n_negative == 0])} | {f(g[g.n_negative == 1])} | "
                           f"{f(g[g.n_weak > 0])} | {f(g[g.position == 'first'])} | {f(g[g.position == 'final'])} | {worst} |")
    q = RESULTS / "pair_predictions.csv"
    if q.is_file():
        pp = pd.read_csv(q)
        pp = pp[pp.run.str.startswith("fixed")]
        pp["model"] = pp.run.str.split("_").str[1]
        out += ["", "## Closest different-local-spin pairs at the same (q, M), both frames in training (fixed regime)", "",
                "Force *difference* between the two frames: DFT vs model; error = RMS of (model diff - DFT diff).", "",
                "| model | pairs | median RMSD (Å) | median D_s | median DFT D_F | median model D_F | median diff error |",
                "|---|---:|---:|---:|---:|---:|---:|"]
        for model, g in pp.groupby("model"):
            out.append(f"| {LABEL[model]} | {len(g)} | {g.rmsd_A.median():.3f} | {g.D_s.median():.2f} | "
                       f"{g.D_F_dft_meV_A.median():.1f} | {g.D_F_model_meV_A.median():.1f} | {g.diff_error_meV_A.median():.1f} |")
    (RESULTS / "comparison.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
