"""Concrete structure-pair examples for the README (results/examples.md)."""
from __future__ import annotations

import pandas as pd

from common import RESULTS

COLS = ["id_i", "id_j", "M_i", "M_j", "rmsd", "D_s", "D_F", "dE_meV_atom", "neg_site_i", "neg_site_j_mapped"]


def table(df: pd.DataFrame) -> list[str]:
    out = ["| frame i | frame j | M_i | M_j | RMSD (Å) | D_s (μB) | D_F (meV/Å) | ΔE (meV/atom) | antiparallel site i / j |",
           "|---|---|---:|---:|---:|---:|---:|---:|---|"]
    for _, r in df.iterrows():
        site = lambda v: "none" if v < 0 else f"Fe{int(v) + 1}"
        out.append(f"| `{r.id_i}` | `{r.id_j}` | {r.M_i} | {r.M_j} | {r.rmsd:.3f} | {r.D_s:.2f} | "
                   f"{1000 * r.D_F:.1f} | {r.dE_meV_atom:.1f} | {site(r.neg_site_i)} / {site(r.neg_site_j_mapped)} |")
    return out


def dedupe(df: pd.DataFrame, n: int) -> pd.DataFrame:
    """Skip pairs whose rounded metrics repeat (duplicate geometries under several record ids)."""
    key = df[["rmsd", "D_s", "D_F"]].round(3).astype(str).agg("|".join, axis=1)
    return df.loc[~key.duplicated()].head(n)


def main() -> None:
    p = pd.read_csv(RESULTS / "pairs.csv")
    same = p[p.same_state]
    out = ["# Structure-pair examples (generated by s8_examples.py)", "",
           "Atom indices are G09 input order of frame i; frame j is mapped onto i by the "
           "permutation/rotation match.", "",
           "## 1. Closest same-(q, M) pairs whose local-spin patterns differ", ""]
    out += table(dedupe(same[same.D_s >= 1.0].sort_values("rmsd"), 6))
    out += ["", "## 2. Same geometry (RMSD < 0.01 Å), different M (M -> M-2 or M-4 hand-offs)", ""]
    cross = p[(~p.same_state) & (p.rmsd < 0.01)].sort_values("D_s", ascending=False)
    out += table(dedupe(cross, 6))
    out += ["", "## 3. Near-identical same-(q, M) geometries with the largest force difference (same spin pattern)", ""]
    near = same[(same.rmsd < 0.1)].sort_values("D_F", ascending=False)
    out += table(dedupe(near, 6))
    out += ["", "## 4. Same (q, M), antiparallel moment on a different site, smallest RMSD", ""]
    moved = same[(same.neg_site_i >= 0) & (same.neg_site_j_mapped >= 0)
                 & (same.neg_site_i != same.neg_site_j_mapped) & (same.D_s >= 1.0)].sort_values("rmsd")
    out += table(dedupe(moved, 6))
    (RESULTS / "examples.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
